#!/usr/bin/env python3
"""Generate core/engine/FontData.inc: the HUD font atlas as embedded PNG bytes.

Staff-only tool (needs Pillow). The generated file is committed, so students
never run this. Usage:

    python tools/staff/gen_font.py [--font PATH] [--size PX]
"""
import argparse
import io
import pathlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "core" / "engine" / "FontData.inc"
EXTRA = [0x00B7, 0x00B0, 0x00D7, 0x2190, 0x2192, 0x2191, 0x2193, 0x2022, 0x2026]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", default="/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
    parser.add_argument("--size", type=int, default=17)
    args = parser.parse_args()

    font = ImageFont.truetype(args.font, args.size)
    ascent, descent = font.getmetrics()
    codes = list(range(32, 127)) + EXTRA
    pad = 2
    atlas_w = 512
    x = y = pad
    row_h = ascent + descent + pad
    placements = []
    for code in codes:
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        w, h = max(right - left, 0), max(bottom - top, 0)
        advance = font.getlength(ch)
        if x + w + pad > atlas_w:
            x = pad
            y += row_h
        placements.append((code, x, y, w, h, left, top, advance))
        x += w + pad
    atlas_h = 1
    while atlas_h < y + row_h:
        atlas_h *= 2

    image = Image.new("L", (atlas_w, atlas_h), 0)
    draw = ImageDraw.Draw(image)
    for code, gx, gy, w, h, left, top, _ in placements:
        draw.text((gx - left, gy - top), chr(code), font=font, fill=255)

    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    data = buffer.getvalue()

    lines = [
        "// Generated by tools/staff/gen_font.py from " + pathlib.Path(args.font).name +
        f" at {args.size}px. Do not edit by hand.",
        "// clang-format off",
        f"constexpr int kFontAscent = {ascent};",
        f"constexpr int kFontLineHeight = {ascent + descent};",
        "struct FontGlyph { unsigned code; short x, y, w, h, left, top; float advance; };",
        "constexpr FontGlyph kFontGlyphs[] = {",
    ]
    for code, gx, gy, w, h, left, top, advance in placements:
        lines.append(f"    {{0x{code:04X}, {gx}, {gy}, {w}, {h}, {left}, {top}, {advance:.3f}f}},")
    lines.append("};")
    lines.append(f"constexpr unsigned kFontPngSize = {len(data)};")
    lines.append("constexpr unsigned char kFontPng[] = {")
    for k in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[k:k + 20]) + ",")
    lines.append("};")
    lines.append("// clang-format on")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(placements)} glyphs, atlas {atlas_w}x{atlas_h}, png {len(data)} bytes")


if __name__ == "__main__":
    main()
